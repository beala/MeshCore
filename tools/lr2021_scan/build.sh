#!/bin/sh
# Builds the LR2021 scanner (scan_hdr.S + scan.c) and writes it as a C array to
# src/helpers/radiolib/lr2021_scan_blob.h, which the firmware loads into the radio's Patch RAM.
# Needs the ARC GCC docker image from lr2021-re-public:
#   docker build -t arc-gcc -f docker/Dockerfile.gcc docker
set -e
cd "$(dirname "$0")"
docker run --rm -u "$(id -u):$(id -g)" -v "$PWD":/w -w /w arc-gcc sh -c '
  CF="-mcpu=em4_dmips -mrf16 -mno-sdata -Os -ffreestanding -fno-builtin -fno-tree-loop-distribute-patterns -fno-pic -fcall-saved-blink"
  arc-linux-gnu-gcc -mcpu=em4_dmips -mrf16 -c -o scan_hdr.o scan_hdr.S &&
  arc-linux-gnu-gcc $CF -Wall -Wextra -Werror -c scan.c -o scan.o &&
  arc-linux-gnu-ld -EL -T pram.ld -o scan.elf scan_hdr.o scan.o &&
  arc-linux-gnu-objcopy -O binary scan.elf scan.bin &&
  arc-linux-gnu-size -A scan.elf | awk "/^.bss/ { if (\$2 != 0) { print \".bss is not empty\"; exit 1 } }"'
rm -f scan_hdr.o scan.o scan.elf
python3 - <<'EOF'
import struct
blob = open('scan.bin', 'rb').read()
blob += b'\0' * (-len(blob) % 4)
words = struct.unpack(f'<{len(blob) // 4}I', blob)
out = ['// Generated by tools/lr2021_scan/build.sh from tools/lr2021_scan/scan.c. Do not edit.',
       '// LR2021 Patch RAM image: on-chip multi-channel LoRa scanner (see scan.c).',
       '#pragma once',
       '#include <stdint.h>',
       '',
       f'static const uint32_t lr2021_scan_blob_words = {len(words)};',
       'static const uint32_t lr2021_scan_blob[] = {']
for i in range(0, len(words), 6):
    out.append('  ' + ', '.join(f'0x{w:08X}' for w in words[i:i + 6]) + ',')
out.append('};')
open('../../src/helpers/radiolib/lr2021_scan_blob.h', 'w').write('\n'.join(out) + '\n')
print(f'scan.bin: {len(blob)} bytes, {len(words)} words')
EOF
rm -f scan.bin
